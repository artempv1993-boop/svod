tot = 0
for u in p['upr']:
    tot += u['docs']
    ppl = f'**{u["people"]}**' if u['people'] is not None else '—'
    w(f'| **{u["name"]}** | **{u["docs"]}** | {ppl} | |')
    for d in u['deps']:
        nm = f'└ *{d["name"]}*' if d['ruk'] else f'└ {d["name"]}'
