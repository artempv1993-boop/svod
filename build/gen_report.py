# --- §4 детализация ---
w('\n---\n\n## 4. Детализация: кто присылал — по управлениям\n')
for u in p['upr']:
    if not u['deps']:
        continue
    w(f'\n### {u["name"]} — {u["docs"]} док.\n')
    for d in u['deps']:
        parts = []
        for f, n, op, bot in d['sub']:
            tag = f' {op}' if op else ''
            tag += ' (чат+бот)' if bot else ''
            parts.append(f'{f} — {n}{tag}')
        for f, n, op in d.get('botNamed', []):
            tag = f' {op}' if op else ''
            parts.append(f'{f} — {n}{tag} *(бот)*')
        if d.get('botUnnamed'):
            parts.append(f'**+{d["botUnnamed"]} из бота — ФИО не определено**')
        if d.get('unresolved'):
            parts.append(f'*автор не установлен — {d["unresolved"]}*')
        nm = 'Руководство управления' if d['ruk'] else d['name']
        head = f'**{nm}** ({d["docs"]} · {d["people"]} чел' + (f' из {d["staff"]}' if d['staff'] else '') + ')'
        w(f'- {head}: ' + ' · '.join(parts))

